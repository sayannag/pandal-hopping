#!/usr/bin/env python3
"""Rebuild the site's data files (data/pandals.js, data/food.js, data/metro.js).

Sources you edit by hand:
  tools/sources/pandals.json        pandal list (name, Bengali name, zone, theme, crowd, notes, location)
  tools/sources/food_curated.json   editorial food picks (must-try dishes, notes, location)
  tools/sources/metro_schedule.json Metro service hours (update when Metro Railway announces Puja timings)

Location of a pandal / curated eatery:
  "osm": "n123" | "w456"  -> exact coordinates fetched from OpenStreetMap (cached in tools/.cache)
  "lat"/"lon"/"prec"      -> explicit coordinates (prec: exact | street | area)

Usage:
  python3 tools/build_data.py                 # rebuild from sources + cache (no network if cache is complete)
  python3 tools/build_data.py --refresh       # re-download OSM food places and anchors
  python3 tools/build_data.py --verify-web    # re-check that website links still work
  python3 tools/build_data.py --refresh-metro # rebuild Metro lines/stations from OpenStreetMap

Food places come from the curated list plus named OpenStreetMap restaurants/cafés/sweet shops within
3 km of a pandal. Data © OpenStreetMap contributors (ODbL). No Google data is stored.
"""
import argparse, concurrent.futures, html, json, math, os, re, ssl, sys, time, urllib.parse, urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'tools', 'sources')
CACHE = os.path.join(ROOT, 'tools', '.cache')
DATA = os.path.join(ROOT, 'data')
UA = 'PujoParikrama/1.0 (static festival guide; data build)'
BBOX = (22.40, 88.20, 22.75, 88.52)
OVERPASS = ['https://overpass-api.de/api/interpreter', 'https://overpass.private.coffee/api/interpreter', 'https://maps.mail.ru/osm/tools/overpass/api/interpreter']
HEADER = '/* Pujo Parikrama — generated by tools/build_data.py. Edit tools/sources/*.json, then rebuild. */\n'
ZONE_ORDER = {'north': 0, 'central': 1, 'south': 2, 'southeast': 3, 'behala': 4, 'east': 5, 'dumdum': 6}


def load(path, default=None):
    try:
        with open(path, encoding='utf-8') as fh:
            return json.load(fh)
    except FileNotFoundError:
        return default


def save(path, obj):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', encoding='utf-8') as fh:
        json.dump(obj, fh, ensure_ascii=False)


def hav(a, b):
    la1, lo1, la2, lo2 = map(math.radians, (a[0], a[1], b[0], b[1]))
    x = math.sin((la2 - la1) / 2) ** 2 + math.cos(la1) * math.cos(la2) * math.sin((lo2 - lo1) / 2) ** 2
    return 2 * 6371.0088 * math.asin(math.sqrt(x))


def overpass(query):
    data = urllib.parse.urlencode({'data': query}).encode()
    for url in OVERPASS:
        for attempt in range(3):
            try:
                req = urllib.request.Request(url, data=data, headers={'User-Agent': UA, 'Accept': 'application/json'})
                with urllib.request.urlopen(req, timeout=240) as r:
                    body = r.read()
                if body[:1] == b'{':
                    return json.loads(body)
            except Exception as ex:  # busy mirrors are common; back off and retry
                print(f'  overpass {url} attempt {attempt + 1}: {ex}', file=sys.stderr)
            time.sleep(8 * (attempt + 1))
    raise SystemExit('Overpass API unavailable — try again later.')


def refresh_food():
    s, w, n, e = BBOX
    q = f'''[out:json][timeout:180];(
      nwr["amenity"~"^(restaurant|cafe|fast_food|food_court|ice_cream)$"]["name"]({s},{w},{n},{e});
      nwr["shop"~"^(confectionery|bakery|pastry|sweets|deli)$"]["name"]({s},{w},{n},{e}););out center tags;'''
    print('Downloading OpenStreetMap food places…')
    save(os.path.join(CACHE, 'osm_food.json'), overpass(q))


def ensure_anchors(ids, refresh):
    anchors = load(os.path.join(CACHE, 'osm_anchors.json'), {}) or {}
    missing = [i for i in ids if refresh or i not in anchors]
    if missing:
        nodes = ','.join(i[1:] for i in missing if i[0] == 'n')
        ways = ','.join(i[1:] for i in missing if i[0] == 'w')
        parts = (f'node(id:{nodes});' if nodes else '') + (f'way(id:{ways});' if ways else '')
        print(f'Fetching {len(missing)} OpenStreetMap anchors…')
        for el in overpass(f'[out:json][timeout:120];({parts});out center tags;')['elements']:
            c = el.get('center', el)
            anchors[el['type'][0] + str(el['id'])] = {'lat': round(c['lat'], 7), 'lon': round(c['lon'], 7), 'name': el.get('tags', {}).get('name', '')}
        save(os.path.join(CACHE, 'osm_anchors.json'), anchors)
    lost = [i for i in ids if i not in anchors]
    if lost:
        raise SystemExit(f'OpenStreetMap ids not found (deleted?): {lost} — replace them with lat/lon in the sources.')
    return anchors


CHAINS = re.compile(r"\b(kfc|domino|mcdonald|pizza hut|burger king|subway|starbucks|cafe coffee day|ccd|barista|wow!? ?momo|haldiram|monginis|mio amore|kathleen|keventers|barbeque nation|chowman|taco bell|blue tokai|bean stop|chai break|baskin|naturals|cream ?bell|amul|the belgian waffle|faasos|behrouz|biryani by kilo|chaayos|third wave|tea villa|krispy|dunkin|burger singh|wendy|la pino|oven story|hocco|mainland china|mamagoto|kouzina)", re.I)


def classify(t):
    n = (t.get('name') or '').lower()
    cu = (t.get('cuisine') or '').lower().replace('_', ' ')
    am, sh, s = t.get('amenity'), t.get('shop'), n + ' | ' + cu
    if 'cabin' in n:
        return 'cabin'
    if sh in ('confectionery', 'sweets') or re.search(r'sweet|mishti|misti|mistanna|mishtanna|bhandar|rosogolla|rasgulla|sandesh|haldiram|bancharam|ganguram|k\.? ?c\.? das|balaram', n) or re.search(r'sweet|dessert|mithai', cu):
        if not re.search(r'cake|bakery|pastry|ice cream', n):
            return 'sweets'
    if sh in ('bakery', 'pastry', 'deli') or am in ('cafe', 'ice_cream') or re.search(r'caf[eé]|coffee|bakery|bakers|cake|patisserie|\btea\b|chai|keventers|monginis|mio amore|kathleen|flurys|starbucks|barista|juice|shake|ice ?cream|creamery|waffle|dessert', n) or re.search(r'coffee|ice cream|cake|juice|tea|bubble', cu):
        return 'cafe'
    if re.search(r'biryani|biriyani|mughlai|mughal|moghul|kebab|kabab|awadhi|nawab|arsalan|aminia|shiraz|zeeshan|rezala|haleem|chaap|tandoor|lucknow|hyderabadi|afghan|persian|arabian', s):
        return 'mughlai'
    if re.search(r'chinese|china|wok|momo|tibet|thai|asian|noodle|dim ?sum|chowman|mamagoto|hakka|beijing|tangra|sushi|japan|korea|burmese|bhutan|nepal', s):
        return 'chinese'
    if re.search(r'roll|phuchka|fuchka|puchka|chaat|kathi|kati|street|telebhaja|chop|cutlet|egg|chowmin|ghugni', n):
        return 'street'
    if re.search(r'bengali|bangali|regional|bhojohori|kasturi|ballygunge place|bhooter|aaheli|tero parbon|saptapadi|bijoli|suruchi|sholo ana|hangla|bhojon|thali|machh|ilish|pice hotel|bhaater', s):
        return 'bengali'
    if am == 'fast_food' and not CHAINS.search(n) and re.search(r'indian|regional|chicken|snack', s):
        return 'street'
    return 'multi'


SPAM = re.compile(r'casino|\bbet\b|betting|slot|for sale|gambl|game bài|đổi thưởng|domain|parked|loan|viagra|porn|togel|judi|poker|crypto|forex', re.I)


def verify_websites(urls):
    ctx = ssl.create_default_context()

    def check(item):
        key, url = item
        try:
            req = urllib.request.Request(url, headers={'User-Agent': 'Mozilla/5.0', 'Accept': 'text/html'})
            with urllib.request.urlopen(req, timeout=12, context=ctx) as r:
                body = r.read(200000).decode('utf-8', 'ignore')
                m = re.search(r'<title[^>]*>(.*?)</title>', body, re.S | re.I)
                title = html.unescape(m.group(1)).strip() if m else ''
                return key, url, r.status < 400 and not SPAM.search(title + ' ' + body[:3000])
        except Exception as ex:
            return key, url, getattr(ex, 'code', None) in (401, 403, 405, 406, 429)
    with concurrent.futures.ThreadPoolExecutor(16) as pool:
        return {k: u for k, u, ok in pool.map(check, urls.items()) if ok}


def build_pandals(src, anchors):
    out = []
    for x in src:
        r = {k: x[k] for k in ('id', 'name', 'bn', 'area', 'zone') if k in x}
        if x.get('osm'):
            a = anchors[x['osm']]
            r.update(lat=round(a['lat'], 6), lon=round(a['lon'], 6), prec='exact')
        else:
            r.update(lat=x['lat'], lon=x['lon'], prec=x.get('prec', 'area'))
        for k in ('tags', 'crowd', 'since', 'theme', 'note'):
            if x.get(k) not in (None, '', []):
                r[k] = x[k]
        r['src'] = 'osm:' + x['osm'] if x.get('osm') else 'manual'
        out.append(r)
    out.sort(key=lambda p: (ZONE_ORDER.get(p['zone'], 9), p['name']))
    ids = [p['id'] for p in out]
    dup = {i for i in ids if ids.count(i) > 1}
    if dup:
        raise SystemExit(f'Duplicate pandal ids: {dup}')
    return out


def build_food(curated, osm_food, anchors, web_ok, pandals):
    by_id = {e['type'][0] + str(e['id']): e for e in osm_food['elements']}
    used = {c['osm'] for c in curated if c.get('osm')}
    out = []
    for c in curated:
        r = {k: v for k, v in c.items() if k != 'osm'}
        if c.get('osm'):
            a = anchors[c['osm']]
            r.update(lat=round(a['lat'], 6), lon=round(a['lon'], 6), prec='exact')
            tags = by_id.get(c['osm'], {}).get('tags', {})
            if not r.get('web'):
                w = web_ok.get(c['osm'])
                if w and not re.search(r'g\.co/|google\.', w):
                    r['web'] = w
            if tags.get('opening_hours'):
                r['hours'] = tags['opening_hours']
        r['src'] = 'curated'
        out.append(r)
    skip = re.compile(r'^(street food stalls?|food stall|tea stall|stall|canteen|mess)$', re.I)
    pts = [(p['lat'], p['lon']) for p in pandals]
    for k, e in by_id.items():
        if k in used or k == 'n1833181230':  # duplicate of the curated Bar-B-Q
            continue
        t = e.get('tags', {})
        name = (t.get('name') or '').strip()
        if not name or skip.match(name):
            continue
        c = e.get('center', e)
        if min(hav((c['lat'], c['lon']), p) for p in pts) > 3.0:
            continue
        r = {'id': 'osm-' + k, 'name': name, 'cat': classify(t), 'lat': round(c['lat'], 6), 'lon': round(c['lon'], 6), 'prec': 'exact', 'src': 'osm', 'osm': k}
        if t.get('cuisine'):
            r['cuisine'] = t['cuisine'].replace('_', ' ').replace(';', ', ')
        if t.get('opening_hours'):
            r['hours'] = t['opening_hours']
        addr = ' '.join(v for v in (t.get('addr:housenumber'), t.get('addr:street')) if v)
        if addr and len(addr) < 80:
            r['addr'] = addr
        w = web_ok.get(k)
        if w and not re.search(r'g\.co/|google\.|yoga|iskcon', w):
            r['menu' if re.search(r'zomato\.com|swiggy\.com', w) else 'web'] = w
        if CHAINS.search(name):
            r['chain'] = 1
        out.append(r)
    out.sort(key=lambda f: (0 if f['src'] == 'curated' else 1, f['name'].lower()))
    return out


PANDAL_KEYS = ['id', 'name', 'bn', 'area', 'zone', 'lat', 'lon', 'prec', 'tags', 'crowd', 'since', 'theme', 'note', 'src']
FOOD_KEYS = ['id', 'name', 'cat', 'area', 'lat', 'lon', 'prec', 'tier', 'hub', 'must', 'why', 'price', 'since', 'cuisine', 'hours', 'addr', 'web', 'menu', 'chain', 'src', 'osm']


def write_js(name, var, rows, keys):
    lines = [json.dumps({k: r[k] for k in keys if k in r and r[k] not in (None, '', [])}, ensure_ascii=False, separators=(',', ':')) for r in rows]
    with open(os.path.join(DATA, name), 'w', encoding='utf-8') as fh:
        fh.write(HEADER + 'window.PP_DATA=window.PP_DATA||{};\nPP_DATA.' + var + '=[\n' + ',\n'.join(lines) + '\n];\n')


def write_metro(schedule):
    built = load(os.path.join(CACHE, 'metro_built.json'))
    if not built:
        print('No cached Metro network — run with --refresh-metro.')
        return
    with open(os.path.join(DATA, 'metro.js'), 'w', encoding='utf-8') as fh:
        fh.write(HEADER + 'window.PP_DATA=window.PP_DATA||{};\nPP_DATA.metro=' + json.dumps({'lines': built['lines'], 'stations': built['stations'], 'schedule': schedule}, ensure_ascii=False, separators=(',', ':')) + ';\n')


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--refresh', action='store_true', help='re-download OpenStreetMap food places and anchors')
    ap.add_argument('--verify-web', action='store_true', help='re-check website links')
    ap.add_argument('--refresh-metro', action='store_true', help='rebuild Metro network from OpenStreetMap (see tools/metro_from_osm.py)')
    args = ap.parse_args()

    pandal_src = load(os.path.join(SRC, 'pandals.json'))
    curated = load(os.path.join(SRC, 'food_curated.json'))
    schedule = load(os.path.join(SRC, 'metro_schedule.json'))
    if args.refresh or not os.path.exists(os.path.join(CACHE, 'osm_food.json')):
        refresh_food()
    osm_food = load(os.path.join(CACHE, 'osm_food.json'))
    ids = sorted({x['osm'] for x in pandal_src + curated if x.get('osm')})
    anchors = ensure_anchors(ids, args.refresh)

    web_ok = load(os.path.join(CACHE, 'web_ok.json'), {}) or {}
    if args.verify_web:
        urls = {}
        for e in osm_food['elements']:
            t = e.get('tags', {})
            w = (t.get('website') or t.get('contact:website') or t.get('url') or '').strip().split(';')[0]
            if w:
                urls[e['type'][0] + str(e['id'])] = w if w.startswith('http') else 'https://' + w
        for c in curated:
            if c.get('web'):
                urls['cur:' + c['id']] = c['web']
        print(f'Checking {len(urls)} websites…')
        web_ok = verify_websites(urls)
        save(os.path.join(CACHE, 'web_ok.json'), web_ok)

    pandals = build_pandals(pandal_src, anchors)
    food = build_food(curated, osm_food, anchors, web_ok, pandals)
    write_js('pandals.js', 'pandals', pandals, PANDAL_KEYS)
    write_js('food.js', 'food', food, FOOD_KEYS)
    if args.refresh_metro:
        import subprocess
        subprocess.run([sys.executable, os.path.join(ROOT, "tools", "metro_from_osm.py")], check=True)
    if schedule:
        write_metro(schedule)
    print(f'Wrote {len(pandals)} pandals and {len(food)} food places to data/.')


if __name__ == '__main__':
    main()
